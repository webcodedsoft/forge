export async function setProjectConnections(projectId: string, ids: string[]) {
  if (activeRunId(projectId)) throw new RunConflictError("Wait for the agent to finish before changing API connections.");
  const unique = [...new Set(ids)];
  if (unique.length) {
    const found = await db.select({ id: schema.apiConnection.id }).from(schema.apiConnection).where(inArray(schema.apiConnection.id, unique));
    if (found.length !== unique.length) throw new ConnectionError("Unknown API connection.");
  }
  await db.transaction(async (tx) => {
    await tx.delete(schema.projectApiConnection).where(eq(schema.projectApiConnection.projectId, projectId));
    if (unique.length) await tx.insert(schema.projectApiConnection).values(unique.map((connectionId) => ({ projectId, connectionId })));
  });
  await syncProjectApis(projectId, "Update API connections");
  return unique;
}

/* ------------------------------ code generation ----------------------------- */

/** Regenerate the project's API files and commit them (generated paths only). */
export async function syncProjectApis(projectId: string, message: string) {
  await ensureSandbox(projectId);
  const rows = await db
    .select({ c: schema.apiConnection })
    .from(schema.projectApiConnection)
    .innerJoin(schema.apiConnection, eq(schema.apiConnection.id, schema.projectApiConnection.connectionId))
    .where(eq(schema.projectApiConnection.projectId, projectId))
    .orderBy(schema.apiConnection.name);
  const conns = rows.map((r) => r.c);

  // Start from a clean slate so removed connections disappear.
  await exec(projectId, [
    "sh",
    "-c",
    "rm -rf .forge/apis src/lib/forge-api src/app/api/forge .env.development.local",
  ]);

  if (conns.length) {
    const files: { path: string; content: string }[] = [];
    for (const c of conns) {
      const spec = c.spec as Spec;
      const types = astToString(await openapiTS(spec as never, { alphabetize: true }));
      files.push({ path: `.forge/apis/${c.name}.openapi.json`, content: JSON.stringify(spec, null, 2) });
      files.push({ path: `src/lib/forge-api/${c.name}.types.ts`, content: `// ${GENERATED}\n\n${types}` });
      files.push({ path: `src/lib/forge-api/${c.name}.ts`, content: clientFile(c.name) });
      files.push({ path: `src/lib/forge-api/${c.name}.server.ts`, content: serverFile(c.name) });
    }
    files.push({ path: "src/app/api/forge/[connection]/[...path]/route.ts", content: proxyRoute(conns.map((c) => c.name)) });
    files.push({ path: ".forge/apis/README.md", content: readme(conns) });
    await putFiles(projectId, files);
  }

  // Commit only the generated paths, so unrelated unsaved work is never swept in.
  const paths = [".forge/apis", "src/lib/forge-api", "src/app/api/forge"];
  const r = await exec(projectId, [
    "sh",
    "-c",
    'git add -A -- "$@" && if git diff --cached --quiet -- "$@"; then echo NOCHANGE; else git commit -q -m "$0" -- "$@" && git rev-parse HEAD; fi',
    message,
    ...paths,
  ]);
  const out = r.stdout.trim();
  if (r.exitCode !== 0) throw new Error(`Committing API files failed: ${r.stderr || out}`);
  if (out !== "NOCHANGE") {
    await appendEvent({ type: "commit", projectId, runId: `apis-${newId().slice(0, 8)}`, sha: out.split("\n").pop()!, message });
  }
}

function clientFile(name: string) {
  return `// ${GENERATED}
import createClient from "openapi-fetch";
import type { paths } from "./${name}.types";

/**
 * Typed client for the "${name}" API, for Client Components ("use client").
 * Requests go through this app's /api/forge/${name} route, which adds the
 * signed-in user's token, so no secrets reach the browser.
 *
 *   const { data, error } = await ${name}Api.GET("/some/path", { params: { query: { ... } } });
 */
export const ${name}Api = createClient<paths>({ baseUrl: "/api/forge/${name}" });
`;
}

function serverFile(name: string) {
  return `// ${GENERATED}
import createClient from "openapi-fetch";
import { headers } from "next/headers";
import type { paths } from "./${name}.types";

/**
 * Typed client for the "${name}" API, for Server Components and route handlers.
 * Calls go through Forge's API gateway, which signs them (API key, token, OAuth or the
 * signed-in user), so no credentials live in this app. Reading request headers makes the
 * caller dynamic: wrap Server Components that use it in <Suspense>.
 *
 *   const api = await ${name}ServerApi();
 *   const { data, error } = await api.GET("/some/path");
 */
export async function ${name}ServerApi() {
  const user = (await headers()).get("x-forge-access-token");
  return createClient<paths>({
    baseUrl: \`\${process.env.FORGE_DATA_URL}/api/${name}\`,
    headers: {
      authorization: \`Bearer \${process.env.FORGE_DATA_TOKEN}\`,
      ...(user ? { "x-forge-user-token": user } : {}),
    },
  });
}
`;
}

function proxyRoute(names: string[]) {
  return `// Generated by Forge. Do not edit.
// Forwards /api/forge/<connection>/<path> to Forge's API gateway, which signs the call with the
// connection's credentials (or the signed-in user's token). No credentials live in this app.
import type { NextRequest } from "next/server";

const CONNECTIONS = new Set(${JSON.stringify(names)});
const FORWARD_REQUEST = ["accept", "accept-language", "content-type", "if-none-match"];
const FORWARD_RESPONSE = ["cache-control", "content-type", "etag", "last-modified", "location", "content-disposition"];

async function proxy(req: NextRequest, ctx: { params: Promise<{ connection: string; path: string[] }> }) {
  const { connection, path } = await ctx.params;
  if (!CONNECTIONS.has(connection)) return Response.json({ error: \`Unknown API connection: \${connection}\` }, { status: 404 });
  const gateway = process.env.FORGE_DATA_URL;
  const token = process.env.FORGE_DATA_TOKEN;
  if (!gateway || !token) return Response.json({ error: "Forge's API gateway isn't available here." }, { status: 503 });

  const url = new URL(\`\${gateway}/api/\${connection}/\${path.map(encodeURIComponent).join("/")}\`);
  url.search = req.nextUrl.search;

  const headers = new Headers({ authorization: \`Bearer \${token}\` });
  for (const h of FORWARD_REQUEST) {
    const v = req.headers.get(h);
    if (v) headers.set(h, v);
  }
  const user = req.headers.get("x-forge-access-token");
  if (user) headers.set("x-forge-user-token", user);

  const hasBody = req.method !== "GET" && req.method !== "HEAD";
  const res = await fetch(url, {
    method: req.method,
    headers,
    body: hasBody ? await req.arrayBuffer() : undefined,
    redirect: "manual",
    cache: "no-store",
  });

  const out = new Headers();
  for (const h of FORWARD_RESPONSE) {
    const v = res.headers.get(h);
    if (v) out.set(h, v);
  }
  return new Response(res.body, { status: res.status, headers: out });
}

export { proxy as DELETE, proxy as GET, proxy as PATCH, proxy as POST, proxy as PUT };
`;
}

const SIGN_IN_TEXT: Record<string, string> = {
  none: "no authentication",
  entra_user: "calls run as the signed-in user (company SSO)",
  api_key: "an API key",
  bearer: "a fixed access token",
  basic: "a username and password",
  oauth2_client: "OAuth 2 client credentials",
  login: "a username and password; Forge logs in and sends the token on every call",
};

function readme(conns: (typeof schema.apiConnection.$inferSelect)[]) {
  const parts = [
    "# API connections",
    "",
    "Generated by Forge. These are the in-house APIs this app may use. Do not edit this file.",
    "",
    "- Client Components: `import { <name>Api } from \"@/lib/forge-api/<name>\"`, then `await <name>Api.GET(\"/path\", { params })`.",
    "- Server Components / route handlers: `import { <name>ServerApi } from \"@/lib/forge-api/<name>.server\"`, then `const api = await <name>ServerApi()`. Wrap such Server Components in `<Suspense>`.",
    "- Calls return `{ data, error, response }`. Show loading, empty and error states; 401/403 means the user may not see that data.",
    "- Only use operations listed in the spec. If something you need is missing, tell the user instead of inventing an endpoint.",
    "",
  ];
  for (const c of conns) {
    const spec = c.spec as Spec;
    parts.push(`## \`${c.name}\`: ${spec.info?.title ?? c.name}${spec.info?.version ? ` (v${spec.info.version})` : ""}`, "");
    if (spec.info?.description) parts.push(spec.info.description.trim().split("\n").slice(0, 8).join("\n"), "");
    parts.push(
      `- Import: \`${c.name}Api\` from \`@/lib/forge-api/${c.name}\`, \`${c.name}ServerApi\` from \`@/lib/forge-api/${c.name}.server\``,
      `- Full spec: \`.forge/apis/${c.name}.openapi.json\` (request/response schemas are typed in \`src/lib/forge-api/${c.name}.types.ts\`)`,
      `- Sign-in: ${SIGN_IN_TEXT[c.authMode] ?? "none"}. Forge adds it to every call; never add credentials yourself.`,
      "",
      "| Method | Path | Summary |",
      "|---|---|---|",
    );
    const rows: string[] = [];
    for (const [path, item] of Object.entries(spec.paths ?? {})) {
      for (const [method, op] of Object.entries(item ?? {})) {
        if (!HTTP_METHODS.includes(method)) continue;
        const sum = (op?.summary ?? op?.operationId ?? "").replace(/\|/g, "/").replace(/\s+/g, " ").slice(0, 100);
        rows.push(`| ${method.toUpperCase()} | \`${path}\` | ${sum} |`);
      }
    }
    parts.push(...rows.slice(0, 300));
    if (rows.length > 300) parts.push(`| … | ${rows.length - 300} more in the spec | |`);
    parts.push("");
  }
  return parts.join("\n");
}
