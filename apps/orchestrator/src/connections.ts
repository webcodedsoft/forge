/*
 * API connections: our in-house REST APIs, registered once for the team with
 * their OpenAPI spec. A project enables some of them; Forge then writes into the
 * project's repo:
 *   .forge/apis/README.md, .forge/apis/<name>.openapi.json   (for the agent)
 *   src/lib/forge-api/<name>.types.ts                        (openapi-typescript)
 *   src/lib/forge-api/<name>.ts, <name>.server.ts            (openapi-fetch clients)
 *   src/app/api/forge/[connection]/[...path]/route.ts        (server proxy)
 * Every call goes through Forge's API gateway (api-gateway.ts), which signs it with the
 * connection's credentials, so no key, token or password ever enters the project.
 */

export const CONNECTION_NAME = /^[a-z][a-z0-9]{1,30}$/;
const newId = customAlphabet("0123456789abcdefghijklmnopqrstuvwxyz", 12);
const MAX_SPEC_BYTES = 10 * 1024 * 1024;
const GENERATED = "Generated by Forge from the API's OpenAPI spec. Do not edit.";

export class ConnectionError extends Error {}

type Spec = {
  openapi?: string;
  info?: { title?: string; version?: string; description?: string };
  paths?: Record<string, Record<string, SpecOperation>>;
};
type SpecParam = { name?: string; in?: string; required?: boolean; $ref?: string };
type SpecOperation = {
  summary?: string;
  operationId?: string;
  description?: string;
  tags?: string[];
  deprecated?: boolean;
  parameters?: SpecParam[];
  requestBody?: unknown;
};

/* ------------------------------ spec loading ------------------------------ */

export async function fetchSpec(specUrl: string): Promise<Spec> {
  let url: URL;
  try {
    url = new URL(specUrl);
  } catch {
    throw new ConnectionError("The spec URL is not a valid URL.");
  }
  if (url.protocol !== "https:" && url.protocol !== "http:") throw new ConnectionError("The spec URL must be http(s).");
  const res = await fetch(url, { signal: AbortSignal.timeout(20_000), headers: { accept: "application/json, application/yaml, text/yaml, */*" } }).catch(
    (e) => {
      throw new ConnectionError(`Could not download the spec: ${e.message}`);
    },
  );
  if (!res.ok) throw new ConnectionError(`Could not download the spec: HTTP ${res.status}`);
  return parseSpec(await res.text());
}

/** A spec from text (a downloaded or uploaded JSON or YAML file). */
export function parseSpec(text: string): Spec {
  if (text.length > MAX_SPEC_BYTES) throw new ConnectionError("The spec is larger than 10 MB.");
  let spec: Spec;
  try {
    spec = text.trimStart().startsWith("{") ? JSON.parse(text) : parseYaml(text);
  } catch (e) {
    throw new ConnectionError(`The spec is not valid JSON or YAML: ${(e as Error).message}`);
  }
  if (!spec || typeof spec !== "object" || !String(spec.openapi ?? "").startsWith("3")) {
    throw new ConnectionError("Only OpenAPI 3.x specs are supported (no \"openapi: 3.x\" field found).");
  }
  return spec;
}

const operationCount = (spec: Spec | null) =>
  Object.values(spec?.paths ?? {}).reduce(
    (n, item) => n + Object.keys(item ?? {}).filter((m) => HTTP_METHODS.includes(m)).length,
    0,
  );
const HTTP_METHODS = ["get", "post", "put", "patch", "delete"];

/** One API for its details page: summary, description, who added it, and the projects using it. */
export async function getConnection(id: string): Promise<ApiConnectionDetails> {
  const [row] = await db
    .select({ c: schema.apiConnection, by: schema.user.name })
    .from(schema.apiConnection)
    .leftJoin(schema.user, eq(schema.user.id, schema.apiConnection.createdBy))
    .where(eq(schema.apiConnection.id, id));
  if (!row) throw new ConnectionError("That API no longer exists.");
  const usedBy = await db
    .select({ id: schema.project.id, name: schema.project.name })
    .from(schema.projectApiConnection)
    .innerJoin(schema.project, eq(schema.project.id, schema.projectApiConnection.projectId))
    .where(eq(schema.projectApiConnection.connectionId, id))
    .orderBy(schema.project.name);
  const spec = row.c.spec as Spec | null;
  return {
    ...summary(row.c),
    description: spec?.info?.description?.trim().slice(0, 4000) || null,
    createdBy: row.by ?? "someone",
    createdAt: row.c.createdAt.toISOString(),
    usedBy,
  };
}

/** The endpoints of a registered API, for people browsing it (Settings › API connections). */
export async function listOperations(id: string): Promise<ApiOperation[]> {
  const [row] = await db.select({ spec: schema.apiConnection.spec }).from(schema.apiConnection).where(eq(schema.apiConnection.id, id));
  if (!row) throw new ConnectionError("That API no longer exists.");
  const spec = (row.spec ?? null) as Spec | null;
  const ops: ApiOperation[] = [];
  for (const [path, item] of Object.entries(spec?.paths ?? {})) {
    // Parameters on the path apply to every method under it.
    const shared = ((item as { parameters?: SpecParam[] }).parameters ?? []) as SpecParam[];
    for (const method of HTTP_METHODS) {
      const op = item?.[method];
      if (!op) continue;
      const params = [...shared, ...(op.parameters ?? [])]
        .filter((p) => p.name && p.in)
        .map((p) => ({ name: p.name!, in: p.in!, required: Boolean(p.required || p.in === "path") }));
      ops.push({
        method: method as ApiOperation["method"],
        path,
        summary: op.summary?.trim() || null,
        description: op.description?.trim().slice(0, 600) || null,
        operationId: op.operationId ?? null,
        tags: (op.tags ?? []).slice(0, 5),
        deprecated: Boolean(op.deprecated),
        parameters: params.slice(0, 30),
        hasBody: Boolean(op.requestBody),
      });
    }
  }
  return ops;
}

/* ------------------------------- CRUD (team) ------------------------------ */

export async function createConnection(input: CreateConnectionInput, userId: string) {
  if (!CONNECTION_NAME.test(input.name)) {
    throw new ConnectionError("Name must be 2-31 lowercase letters or digits, starting with a letter (e.g. hr, billing).");
  }
  try {
    new URL(input.baseUrl);
  } catch {
    throw new ConnectionError("The base URL is not a valid URL.");
  }
  const [dupe] = await db.select({ id: schema.apiConnection.id }).from(schema.apiConnection).where(eq(schema.apiConnection.name, input.name));
  if (dupe) throw new ConnectionError(`A connection named "${input.name}" already exists.`);
  const spec = input.specUrl ? await fetchSpec(input.specUrl) : parseSpec(input.specText ?? "");
  const id = newId();
  const [row] = await db
    .insert(schema.apiConnection)
    .values({
      id,
      name: input.name,
      title: spec.info?.title ?? null,
      baseUrl: input.baseUrl.replace(/\/+$/, ""),
      specUrl: input.specUrl ?? null,
      specFileName: input.specUrl ? null : (input.specFileName ?? "spec.json"),
      spec,
      specFetchedAt: new Date(),
      ...authColumns(id, input.auth),
      createdBy: userId,
    })
    .returning();
  return summary(row!);
}

/** Change the base URL, the sign-in, or replace an uploaded spec. Projects using it are regenerated. */
export async function updateConnection(id: string, input: UpdateConnectionInput) {
  const [row] = await db.select().from(schema.apiConnection).where(eq(schema.apiConnection.id, id));
  if (!row) throw new ConnectionError("Connection not found.");
  const set: Partial<typeof schema.apiConnection.$inferInsert> = {};
  if (input.baseUrl) set.baseUrl = input.baseUrl.replace(/\/+$/, "");
  if (input.auth) Object.assign(set, authColumns(id, input.auth), { lastTest: null });
  if (input.specText) {
    const spec = parseSpec(input.specText);
    Object.assign(set, { spec, title: spec.info?.title ?? row.title, specUrl: null, specFileName: input.specFileName ?? "spec.json", specFetchedAt: new Date(), specError: null });
  }
  if (!Object.keys(set).length) return summary(row);
  await db.update(schema.apiConnection).set(set).where(eq(schema.apiConnection.id, id));
  forgetToken(id);
  if (input.specText) await resyncUsers(id, "Update API spec");
  const [updated] = await db.select().from(schema.apiConnection).where(eq(schema.apiConnection.id, id));
  return summary(updated!);
}

/** Sign in and make one simple call; the result is kept for the page. */
export async function testConnectionById(id: string) {
  const [row] = await db.select().from(schema.apiConnection).where(eq(schema.apiConnection.id, id));
  if (!row) throw new ConnectionError("Connection not found.");
  const result = await testConnection(row);
  await db.update(schema.apiConnection).set({ lastTest: result }).where(eq(schema.apiConnection.id, id));
  return result;
}

async function resyncUsers(id: string, message: string) {
  const users = await db
    .select({ projectId: schema.projectApiConnection.projectId })
    .from(schema.projectApiConnection)
    .where(eq(schema.projectApiConnection.connectionId, id));
  for (const { projectId } of users) {
    if (!activeRunId(projectId)) await syncProjectApis(projectId, message).catch((e) => console.error("sync failed", e));
  }
}

export async function listConnections() {
  const rows = await db.select().from(schema.apiConnection).orderBy(schema.apiConnection.name);
  return rows.map(summary);
}

export async function refreshConnection(id: string) {
  const [row] = await db.select().from(schema.apiConnection).where(eq(schema.apiConnection.id, id));
  if (!row) throw new ConnectionError("Connection not found.");
  if (!row.specUrl) throw new ConnectionError("This API's spec was uploaded as a file. Upload the new file instead.");
  try {
    const spec = await fetchSpec(row.specUrl);
    await db
      .update(schema.apiConnection)
      .set({ spec, title: spec.info?.title ?? row.title, specFetchedAt: new Date(), specError: null })
      .where(eq(schema.apiConnection.id, id));
  } catch (e) {
    await db.update(schema.apiConnection).set({ specError: (e as Error).message }).where(eq(schema.apiConnection.id, id));
    throw e;
  }
  // Regenerate types in every project that uses it (skips projects with a run in progress).
  await resyncUsers(id, "Update API spec");
  const [updated] = await db.select().from(schema.apiConnection).where(eq(schema.apiConnection.id, id));
  return summary(updated!);
}

export async function deleteConnection(id: string) {
  const users = await db
    .select({ projectId: schema.projectApiConnection.projectId })
    .from(schema.projectApiConnection)
    .where(eq(schema.projectApiConnection.connectionId, id));
  if (users.length) throw new ConnectionError(`${users.length} project(s) still use this connection. Remove it from them first.`);
  await db.delete(schema.apiConnection).where(eq(schema.apiConnection.id, id));
  forgetToken(id);
}

function summary(row: typeof schema.apiConnection.$inferSelect): ApiConnection {
  const spec = row.spec as Spec | null;
  return {
    id: row.id,
    name: row.name,
    title: row.title,
    version: spec?.info?.version ?? null,
    baseUrl: row.baseUrl,
    specUrl: row.specUrl,
    specFileName: row.specFileName,
    operations: operationCount(spec),
    specFetchedAt: row.specFetchedAt?.toISOString() ?? null,
    specError: row.specError,
    auth: authSummary(row),
    lastTest: (row.lastTest as ApiConnection["lastTest"]) ?? null,
  };
}

